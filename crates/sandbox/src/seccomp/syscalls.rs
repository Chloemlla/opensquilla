/// Fallback lookup for syscalls that may not be defined in an older `libc`
/// crate on the target, or on non-Linux platforms.
fn fallback_x86_64_lookup(name: &str) -> Option<i64> {
    static TABLE: OnceLock<HashMap<&'static str, i64>> = OnceLock::new();
    let table = TABLE.get_or_init(|| {
        SYSCALL_NAMES.iter().copied().collect::<HashMap<_, _>>()
    });
    table.get(name).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_syscalls_resolve() {
        assert_eq!(syscall_name_to_number("read"), Some(0));
        assert_eq!(syscall_name_to_number("write"), Some(1));
        assert_eq!(syscall_name_to_number("openat"), Some(257));
        assert_eq!(syscall_name_to_number("execve"), Some(59));
    }

    #[test]
    fn unknown_syscall_returns_none() {
        assert_eq!(syscall_name_to_number("not_a_syscall"), None);
    }

    #[test]
    fn table_is_unique() {
        let mut names: Vec<&str> = SYSCALL_NAMES.iter().map(|(n, _)| *n).collect();
        names.sort();
        let len_before = names.len();
        names.dedup();
        assert_eq!(names.len(), len_before, "duplicate syscall names in table");
    }
}
