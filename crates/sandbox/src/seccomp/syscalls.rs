//! Syscall name → number resolution.
//!
//! On Linux we defer to `libc::SYS_*` constants at compile time so the table
//! is always correct for the target architecture. On non-Linux platforms we
//! provide static x86_64 numbers so the filter can still be built (e.g. for
//! tests or cross-compilation), though it would only be installable on Linux.
//!
//! The table is intentionally large: the seccomp builder looks up names here
//! and an unknown name should be a hard error, not a silent skip.

use std::collections::HashMap;
use std::sync::OnceLock;

/// Resolve a syscall name to its number, if known.
///
/// On Linux this consults `libc::SYS_*` for the target architecture. On
/// non-Linux it falls back to a static x86_64 table.
pub fn syscall_name_to_number(name: &str) -> Option<i64> {
    #[cfg(target_os = "linux")]
    {
        linux_lookup(name)
    }
    #[cfg(not(target_os = "linux"))]
    {
        fallback_x86_64_lookup(name)
    }
}

